#!/usr/bin/env python3
"""guard.py — a Claude Code "PreToolUse" hook for this repo.

What it is for
--------------
CLAUDE.md *tells* Claude Code the rules. This script *checks* the few rules whose
mistakes are expensive to undo. Claude Code runs it before every Edit, Write and
Bash call (see .claude/settings.json) and passes the planned call to it as JSON on
standard input.

    exit 0 -> fine, the call goes ahead
    exit 2 -> refused: Claude Code cancels the call and shows our message to Claude
    exit 1 -> the guard itself broke: Claude Code shows a warning and carries on

Why a script and not only CLAUDE.md: an instruction is advice, a check is a
guarantee — the same idea as the database triggers that protect the ledgers
(ADR-0021) and the import-linter contracts that protect the layers (ADR-0015).

What it refuses
---------------
1. Editing generated files: the API types, the changelog, the lock files.   (ADR-0025)
2. Editing a migration that is already on main.                            (03 §9)
3. `migrate` before the custom User's first migration exists (PPL-1).       (ADR-0012)
4. Committing on main, force-pushing, pushing to main.                      (04 §3.4)
5. Skipping the git hooks (`--no-verify`): they check every commit message
   for its `Why:` line, among other things.                                 (04 §3.5)
6. Force-adding ignored files: private/ and .env are ignored on purpose.    (CLAUDE.md rule 10)

Who approves commits is not this script's job: `git commit` is an "ask" rule in
.claude/settings.json, so Claude Code asks Jack before every commit.

It is a safety net for honest mistakes, not a security wall: a command written in an
unusual shape can slip past it. GitHub branch protection is the wall for `main`.

Test it with:  python3 -m unittest discover -s .claude/hooks
"""

from __future__ import annotations

import json
import os
import re
import shlex
import subprocess
import sys
from pathlib import Path

# Files a tool writes for us. Editing them by hand is undone (or broken) by the next run.
GENERATED = {
    "frontend/src/api/schema.d.ts": "it is generated by `pnpm gen:api` (ADR-0025). Change the serializer or view, then regenerate.",
    "CHANGELOG.md": "release-please writes it from the PR titles (04 BP11).",
    "backend/uv.lock": "change dependencies with `uv add` or `uv remove`; they rewrite the lock file.",
    "frontend/pnpm-lock.yaml": "change dependencies with `pnpm add` or `pnpm remove`; they rewrite the lock file.",
}

# backend/apps/<app>/migrations/0003_something.py
MIGRATION = re.compile(r"^backend/apps/[^/]+/migrations/\d{4}_\w+\.py$")

# PPL-1 creates this file. Until it exists, no database may be migrated (ADR-0012, 04 BP5).
FIRST_USER_MIGRATION = "backend/apps/people/migrations/0001_initial.py"

# Shell separators. Splitting a command on them lets us check each part of
# `cd backend && uv run python manage.py migrate` on its own.
SEPARATORS = re.compile(r"&&|\|\||;|\||\n")

# git options that take a value as the next word (`git -C backend commit`).
GIT_OPTIONS_WITH_VALUE = {"-C", "-c", "--git-dir", "--work-tree", "--namespace"}
FORCE_FLAGS = {"-f", "--force", "--force-with-lease", "--force-if-includes"}


def main() -> int:
    try:
        event = json.load(sys.stdin)
    except json.JSONDecodeError as exc:
        print(f"guard.py could not read the hook input ({exc}); this call was not checked.", file=sys.stderr)
        return 1

    root = Path(os.environ.get("CLAUDE_PROJECT_DIR") or event.get("cwd") or ".").resolve()
    tool = event.get("tool_name", "")
    data = event.get("tool_input") or {}

    if tool in ("Edit", "Write", "MultiEdit"):
        problem = check_file_edit(root, str(data.get("file_path", "")))
    elif tool == "Bash":
        problem = check_command(root, str(data.get("command", "")))
    else:
        problem = None

    if problem:
        print(f"Blocked by .claude/hooks/guard.py: {problem}", file=sys.stderr)
        return 2
    return 0


# ----------------------------------------------------------------- file edits
def check_file_edit(root: Path, file_path: str) -> str | None:
    rel = relative_to_root(root, file_path)
    if rel is None:  # outside the repo: not ours to judge
        return None
    if rel in GENERATED:
        return f"{rel} is not edited by hand — {GENERATED[rel]}"
    if MIGRATION.match(rel) and is_on_main(root, rel):
        return (f"{rel} is already on main, and a migration on main is never edited (03 §9). "
                "Write a new migration instead.")
    return None


def relative_to_root(root: Path, file_path: str) -> str | None:
    """The path as `backend/apps/...`, or None when it is outside the repo."""
    if not file_path:
        return None
    path = Path(file_path)
    if not path.is_absolute():
        path = root / path
    try:
        return path.resolve().relative_to(root).as_posix()
    except ValueError:
        return None


def is_on_main(root: Path, rel: str) -> bool:
    """True when the file exists on origin/main (or on the local main, before a remote exists)."""
    for ref in ("origin/main", "main"):
        if git(root, "rev-parse", "--verify", "--quiet", ref) is not None:
            return git(root, "cat-file", "-e", f"{ref}:{rel}") is not None
    return False


# ----------------------------------------------------------------- commands
def check_command(root: Path, command: str) -> str | None:
    for part in SEPARATORS.split(command):
        words = split_words(part)
        if not words:
            continue
        problem = check_git(root, words) or check_migrate(root, words)
        if problem:
            return problem
    return None


def split_words(part: str) -> list[str]:
    """Shell-style words; falls back to plain spaces when quotes don't balance."""
    try:
        return shlex.split(part)
    except ValueError:
        return part.split()


def check_git(root: Path, words: list[str]) -> str | None:
    if "git" not in words:
        return None
    sub, args = git_subcommand(words[words.index("git") + 1:])

    skips_hooks = (sub in ("commit", "push") and "--no-verify" in args) or (sub == "commit" and "-n" in args)
    if skips_hooks:
        return ("the git hooks are never skipped: they check each commit, including its `Why:` line "
                "(04 §3.5). Fix what the hook reports, then commit again.")

    if sub == "commit" and current_branch(root) == "main":
        return ("you are on main, and main only changes through pull requests. "
                "Create the task branch first: git switch -c <branch named on the card> (04 §3.4).")

    if sub == "push":
        if any(a in FORCE_FLAGS or a.startswith("--force") for a in args) or any(
            a.startswith("+") and len(a) > 1 for a in args
        ):
            return ("no force-push (04 §4). If main moved while you worked, bring it in with: "
                    "git fetch origin && git merge origin/main")
        targets = [a for a in args if not a.startswith("-")]
        refspecs = targets[1:]  # the first non-option word is the remote
        branch = current_branch(root)
        if any(pushes_to_main(r, branch) for r in refspecs) or (not refspecs and branch == "main"):
            return "main only changes through pull requests (04 §4). Push the task branch and open a PR."

    if sub == "add" and any(a in ("-f", "--force") for a in args):
        return ("`git add --force` adds ignored files, and private/ and .env are ignored on purpose "
                "(CLAUDE.md rule 10). Add the files you mean by name, without --force.")
    return None


def git_subcommand(words: list[str]) -> tuple[str | None, list[str]]:
    """Skip git's own options (`git -C backend commit …`) and return (subcommand, its arguments)."""
    i = 0
    while i < len(words):
        word = words[i]
        if word in GIT_OPTIONS_WITH_VALUE:
            i += 2
        elif word.startswith("-"):
            i += 1
        else:
            return word, words[i + 1:]
    return None, []


def pushes_to_main(refspec: str, branch: str | None) -> bool:
    destination = refspec.split(":", 1)[1] if ":" in refspec else refspec
    if destination in ("main", "refs/heads/main"):
        return True
    return destination == "HEAD" and branch == "main"


def check_migrate(root: Path, words: list[str]) -> str | None:
    runs_django = any(w.endswith("manage.py") or w in ("django-admin", "make") for w in words)
    if "migrate" in words and runs_django and not (root / FIRST_USER_MIGRATION).exists():
        return ("no `migrate` on any database until PPL-1 — the custom User — is merged: Django can't "
                "swap its user model after the first migration (ADR-0012, 04 BP5).")
    return None


# ----------------------------------------------------------------- git helpers
def current_branch(root: Path) -> str | None:
    """The branch name; works before the first commit too. None when HEAD is detached."""
    return git(root, "symbolic-ref", "--quiet", "--short", "HEAD")


def git(root: Path, *args: str) -> str | None:
    """Run git in the repo; return its output, or None if it failed."""
    try:
        result = subprocess.run(["git", "-C", str(root), *args], capture_output=True, text=True, timeout=5)
    except (OSError, subprocess.TimeoutExpired):
        return None
    return result.stdout.strip() if result.returncode == 0 else None


if __name__ == "__main__":
    sys.exit(main())
